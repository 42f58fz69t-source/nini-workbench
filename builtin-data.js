// 按日期确定性轮换：同一天打开内容一致，跨天自动更新
function studyDayIndex(dateStr) {
  const d = new Date((dateStr || todayStr()) + 'T00:00:00');
  const start = new Date(d.getFullYear() + '-01-01T00:00:00');
  return Math.floor((d - start) / 86400000) + 1; // 年内第几天
}

function studyDailyContent(dateStr, offset) {
  offset = offset || 0;
  const di = studyDayIndex(dateStr) + offset;
  const subject = STUDY_ACTIVE[di % STUDY_ACTIVE.length];
  const bank = STUDY_BANK[subject] || { mcq: [], law: [] };
  const q = bank.mcq.length ? bank.mcq[di % bank.mcq.length] : null;
  const quickArr = STUDY_QUICK[subject] || [];
  const quick = quickArr.length ? quickArr[(di + 7) % quickArr.length] : '';
  const law = (bank.law && bank.law.length) ? bank.law[di % bank.law.length] : '';
  return { subject, question: q, quick, law };
}

// 闪卡素材：本期 3 科的选择题（正面问题/背面答案解析）+ 速记（正面考点/背面提示）
function studyFlashcards() {
  const cards = [];
  STUDY_ACTIVE.forEach(sub => {
    const bank = STUDY_BANK[sub] || { mcq: [] };
    (bank.mcq || []).forEach(m => cards.push({ subject: sub, front: m.q, back: '正确答案：' + String.fromCharCode(65 + m.answer) + '\n' + m.tip }));
    (STUDY_QUICK[sub] || []).forEach(k => cards.push({ subject: sub, front: k, back: '【' + sub + '】考点速记' }));
  });
  return cards;
}
